const languageSelect = document.querySelector(".site-language");
let siteLanguage = "en";
const staticCopy = [];
const copyNodes = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (copyNodes.nextNode()) {
  const node = copyNodes.currentNode;
  const value = node.data.trim();
  if (languageCopy.has(value)) staticCopy.push(() => { node.data = t(value); });
}
for (const element of document.querySelectorAll("[aria-label], [aria-roledescription]")) {
  for (const attribute of ["aria-label", "aria-roledescription"]) {
    const value = element.getAttribute(attribute);
    if (languageCopy.has(value)) staticCopy.push(() => element.setAttribute(attribute, t(value)));
  }
}

function t(english, values = {}) {
  return (languageCopy.get(english)?.[siteLanguage] ?? english)
    .replace(/\{(\w+)\}/g, (placeholder, key) => values[key] ?? placeholder);
}

function scentText(scent, field) {
  return scentCopy.get(scent.id)?.[siteLanguage]?.[field] ?? scent[field];
}

function translateNotes(value) {
  if (siteLanguage === "en") return value;
  return value.split(/\s*&\s*|,\s*|\s+and\s+/i).map(note => t(note)).join(siteLanguage === "ar" ? "، " : ", ");
}

function setSiteLanguage(value) {
  siteLanguage = ["en", "ar", "es"].includes(value) ? value : "en";
  document.documentElement.lang = siteLanguage;
  document.documentElement.dir = siteLanguage === "ar" ? "rtl" : "ltr";
  languageSelect.value = siteLanguage;
  staticCopy.forEach(update => update());
  document.dispatchEvent(new Event("nasaem:language"));
}

